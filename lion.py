from collections import Counter # Подключаем библиотеки и инструмент Counter
import matplotlib.pyplot as plt
import pandas as pd
with open('lion.txt', 'r', encoding='utf-8') as f: # 1. Читаем текст из файла 
    text = f.read()
russ_bukvi = "абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ" # работаем с буквами 
bukvi = [] # пустой список куда будем складывать найденные в тексте буквы
for i in text: # запускаем цикл, который проверяет символы в тексте
    if i in russ_bukvi: # проверяем, является ли  символ русской буквой
        bukvi.append(i) # если да то добавляем эту букву в список
schet_bukv = Counter(bukvi)  # подсчитываем сколько раз каждая буква встретилась в списке
znaki = '.,!?;:"()[]{}«»—' # задаём строку со знаками препинания которые надо удалить
slova = text.split() # разбиваем весь текст на отдельные слова по пробелам и переносам строк
slova1= [] #пустой список для очищенных слов
for s in slova: # запускаем цикл по каждому слову из  списка
    for z in znaki: # внутри запускаем цикл по каждому знаку препинания
        s = s.replace(z, '') # удаляем знаки
    if s != '': # проверяем, не осталось ли слово пустым после удаления всех знаков
        slova1.append(s) # добавляем  слово в итоговый список 
schet_slov = Counter(slova1) # считаем количество повторений для каждого слова
vsego_slov = len(slova1) # вычисляем общее количество всех слов в тексте
spisok_slov = [] # создаём  еще один пустой список но теперь для формирования будущих строк таблицы
for slovo, kolichestvo in schet_slov.items(): # перебираем пары слово и количество его повторений
    chastota = round((kolichestvo / vsego_slov) * 100, 2) # вычисляем слова в процентах и округляем до 2 знаков
    spisok_slov.append((slovo, kolichestvo, chastota)) # добавляем готовую строку из трёх значений в список
tablica = pd.DataFrame(spisok_slov, columns=['Слово', 'Частота встречи, раз', 'Частота встречи в %']) # преобразуем список в таблицу с заданными названиями столбцов
tablica.to_csv('slova.csv', index=False, sep=';', encoding='utf-8-sig') # сохраняем таблицу в CSV-файл без номеров строк с разделителем «;»
plt.hist(bukvi, bins=len(schet_bukv)) # строим гистограмму по списку букв с числом столбцов, равным числу уникальных букв
plt.xlabel('Буквы') # задаём подпись для горизонтальной оси X
plt.ylabel('Количество') # задаём подпись для вертикальной оси Y
plt.show() # выводим окно с готовой гистограммой на экран